"""Generate the power model of the bench from the power intent table (a table of this example, not UPF).

The generated module has three parts: the registers of a domain become X while the domain is
off; the isolated outputs are compared with the value the table gives; the power states and the
order of the control signals are compared with the table.
"""
import json
import re

ISOLATION = ('zero', 'one', 'hold')
MODULE = 'pd_power_model'


def load(path):
    return validate(json.loads(path.read_text()))


def validate(intent):
    if intent.get('schema_version') != 1 or type(intent.get('revision')) is not int or intent['revision'] < 1:
        raise ValueError('unsupported schema_version or invalid revision')
    domains, states, transitions = intent['domains'], intent['states'], intent['transitions']
    names = set()
    if not domains or not states or not transitions:
        raise ValueError('domains, states and transitions are required')
    for key, domain in domains.items():
        if not re.fullmatch(r'[a-z]\w*', key) or set(domain['requires']) - domains.keys() or key in domain['requires']:
            raise ValueError(f'invalid domain {key}')
        if not domain['registers'] or not domain['outputs']:
            raise ValueError(f'domain {key} needs registers and outputs')
        for item in domain['registers'] + domain['outputs']:
            if item['name'] in names or not 1 <= item['width'] <= 32:
                raise ValueError(f"duplicate name or invalid width: {item['name']}")
            names.add(item['name'])
        for register in domain['registers']:
            if type(register['retained']) is not bool or not 0 <= register['reset'] < 1 << register['width']:
                raise ValueError(f"invalid register {register['name']}")
        if any(output['isolation'] not in ISOLATION for output in domain['outputs']):
            raise ValueError(f'unknown isolation value in domain {key}')
    seen = set()
    for name, state in states.items():
        value = tuple(state[key] for key in domains)
        if set(state) != set(domains) or any(v not in (0, 1) for v in value) or value in seen:
            raise ValueError(f'invalid or duplicate state {name}')
        seen.add(value)
        for key, domain in domains.items():
            if state[key] and not all(state[other] for other in domain['requires']):
                raise ValueError(f'state {name} powers {key} without the domains it requires')
    for name, (source, target) in transitions.items():
        if source not in states or target not in states:
            raise ValueError(f'transition {name} uses an unknown state')
        if sum(states[source][key] != states[target][key] for key in domains) != 1:
            raise ValueError(f'transition {name} must switch exactly one domain')
    for crossing in intent.get('crossings', []):
        source, target = crossing['from'], crossing['to']
        if crossing['isolation'] != 'none':
            raise ValueError('a crossing between switched domains is listed only when it has no isolation')
        if any(state[target] and not state[source] for state in states.values()):
            raise ValueError(f"crossing {crossing['signal']} needs isolation: {target} can be on while {source} is off")
    return intent


def audit_registers(intent, rtl_by_instance):
    """Every `reg` of a domain's RTL must be in the table, and the reverse. Independent of generate()."""
    for key, domain in intent['domains'].items():
        text = re.sub(r'//[^\n]*', '', rtl_by_instance[domain['instance']])
        declared = set()
        for names in re.findall(r'^\s*reg\b(?:\s*\[[^\]]*\])?\s*([^;]+);', text, re.M):
            declared.update(name.strip() for name in names.split(','))
        listed = {register['name'] for register in domain['registers']}
        if declared != listed:
            raise ValueError(f'registers of domain {key} differ from the table: {sorted(declared ^ listed)}')


def state_bits(intent, name):
    return ''.join(str(intent['states'][name][key]) for key in intent['domains'])


def generate(intent, drop_injection=()):
    """SystemVerilog text. `drop_injection` leaves registers out of the X injection (self-test only)."""
    scope, lines = intent['scope'], []
    top = scope.split('.')[0]
    add = lines.append
    domains = intent['domains']
    width = len(domains)
    powers = ', '.join(f"{scope}.{domain['power']}" for domain in domains.values())
    add('`timescale 1ns/1ps')
    add('// Generated by gen.py from power_intent.json. Do not edit.')
    add(f"module {MODULE} #(parameter {intent['settle_parameter']} = 2) (input wire clk, input wire rst_n);")
    settle = intent['settle_parameter']
    for key, domain in domains.items():
        power, instance = f"{scope}.{domain['power']}", f"{scope}.{domain['instance']}"
        registers = [r for r in domain['registers'] if f"{key}.{r['name']}" not in drop_injection]
        add(f'    // Domain {key}: registers lose their value while the power is off.')
        add(f'    always @({power}) begin')
        add(f"        if ({power} === 1'b0) begin")
        for register in registers:
            add(f"            force {instance}.{register['name']} = {register['width']}'bx;")
        add(f"        end else if ({power} === 1'b1) begin")
        for register in registers:
            add(f"            release {instance}.{register['name']};")
        add('        end')
        add('    end')
    add('    reg seen;')
    add(f'    reg [{width - 1}:0] prev_state;')
    add(f'    wire [{width - 1}:0] state = {{{powers}}};')
    covers = [f'state/{name}' for name in intent['states']] + [f'transition/{name}' for name in intent['transitions']]
    covers += ['iso/zero', 'iso/one', 'iso/hold-nonzero']
    for key, domain in domains.items():
        add(f'    reg {key}_prev_power, {key}_prev_iso, {key}_prev_reset, {key}_reset_seen;')
        add(f'    integer {key}_up;')
        for register in domain['registers']:
            add(f"    reg [{register['width'] - 1}:0] {key}_{register['name']}_snap;")
            covers.append(f"{'retain' if register['retained'] else 'reinit'}/{key}-{register['name']}")
        for output in domain['outputs']:
            if output['isolation'] == 'hold':
                add(f"    reg [{output['width'] - 1}:0] {output['name']}_held;")
    flags = {name: 'cov_' + re.sub(r'\W', '_', name) for name in covers}

    def cover(name):  # print each goal once
        return f'if (!{flags[name]}) begin {flags[name]} = 1; $display("COVER {name}"); end'
    for flag in flags.values():
        add(f'    reg {flag} = 0;')
    add('    always @(negedge clk) begin')
    add('        if (!rst_n) begin')
    add('            seen <= 0;')
    for key, domain in domains.items():
        add(f'            {key}_up <= 0; {key}_reset_seen <= 0;')
        for register in domain['registers']:
            add(f"            {key}_{register['name']}_snap <= {register['width']}'d{register['reset']};")
        for output in domain['outputs']:
            if output['isolation'] == 'hold':
                add(f"            {output['name']}_held <= 0;")
    add('        end else begin')
    add('            // Legal power states and transitions.')
    add('            case (state)')
    for name in intent['states']:
        add(f"                {width}'b{state_bits(intent, name)}: {cover('state/' + name)}")
    add(f'                default: {top}.fail("PD_STATE");')
    add('            endcase')
    add('            if (seen && state !== prev_state) begin')
    add('                case ({prev_state, state})')
    for name, (source, target) in intent['transitions'].items():
        add(f"                    {2 * width}'b{state_bits(intent, source)}{state_bits(intent, target)}: "
            f"{cover('transition/' + name)}")
    add(f'                    default: {top}.fail("PD_TRANSITION");')
    add('                endcase')
    add('            end')
    for key, domain in domains.items():
        power, iso, reset = (f"{scope}.{domain[name]}" for name in ('power', 'isolate', 'reset_n'))
        instance = f"{scope}.{domain['instance']}"
        add(f'            // Domain {key}: order of isolation, reset and power.')
        add(f"            if ({power} === 1'b0 && ({iso} !== 1'b1 || {reset} !== 1'b0)) {top}.fail(\"PD_SEQ\");")
        add(f"            if (seen && {key}_prev_power === 1'b1 && {power} === 1'b0 && {key}_prev_iso !== 1'b1) {top}.fail(\"PD_SEQ\");")
        add(f"            if (seen && {key}_prev_reset === 1'b0 && {reset} === 1'b1 && {key}_up < {settle}) {top}.fail(\"PD_SEQ\");")
        add(f"            if (seen && {key}_prev_iso === 1'b1 && {iso} === 1'b0) begin")
        add(f"                if ({power} !== 1'b1 || {reset} !== 1'b1 || !{key}_reset_seen || {key}_up < {settle}) {top}.fail(\"PD_SEQ\");")
        for register in domain['registers']:
            name, snap = f"{instance}.{register['name']}", f"{key}_{register['name']}_snap"
            value = f"{register['width']}'d{register['reset']}"
            if register['retained']:
                add(f'                if ({name} !== {snap}) {top}.fail("PD_RETAIN");')
            else:
                add(f'                if ({name} !== {value}) {top}.fail("PD_INIT");')
            goal = f"{'retain' if register['retained'] else 'reinit'}/{key}-{register['name']}"
            add(f'                if ({snap} != {value}) {cover(goal)}')
        add('            end')
        add(f"            if ({power} === 1'b1) {key}_up <= {key}_up + 1; else {key}_up <= 0;")
        add(f"            if ({power} !== 1'b1) {key}_reset_seen <= 0; else if ({reset} === 1'b0) {key}_reset_seen <= 1;")
        add(f"            {key}_prev_power <= {power}; {key}_prev_iso <= {iso}; {key}_prev_reset <= {reset};")
    add('            // No X on any output of the always-on domain.')
    outputs = list(intent['always_on_outputs']) + [o for d in domains.values() for o in d['outputs']]
    for output in outputs:
        add(f"            if (^{scope}.{output['name']} === 1'bx) {top}.fail(\"PD_XLEAK\");")
    for key, domain in domains.items():
        power, iso = f"{scope}.{domain['power']}", f"{scope}.{domain['isolate']}"
        instance = f"{scope}.{domain['instance']}"
        add(f'            // Domain {key}: isolation values, and what is remembered while the domain is on.')
        add(f"            if ({iso} === 1'b1) begin")
        for output in domain['outputs']:
            signal, kind = f"{scope}.{output['name']}", output['isolation']
            expected = {'zero': f"{output['width']}'d0", 'one': f"{{{output['width']}{{1'b1}}}}",
                        'hold': f"{output['name']}_held"}[kind]
            add(f'                if ({signal} !== {expected}) {top}.fail("PD_ISO");')
            condition = f"{power} === 1'b0" + (f" && {output['name']}_held != 0" if kind == 'hold' else '')
            add(f"                if ({condition}) {cover('iso/hold-nonzero' if kind == 'hold' else 'iso/' + kind)}")
        add(f"            end else if ({power} === 1'b1) begin")
        for register in domain['registers']:
            add(f"                {key}_{register['name']}_snap <= {instance}.{register['name']};")
        for output in domain['outputs']:
            if output['isolation'] == 'hold':
                add(f"                {output['name']}_held <= {scope}.{output['name']};")
        add('            end')
    add('            prev_state <= state;')
    add('            seen <= 1;')
    add('        end')
    add('    end')
    add('endmodule')
    return '\n'.join(lines) + '\n'
