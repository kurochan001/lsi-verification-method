def add_arguments(parser):
    default = ROOT / 'artifacts/toolchains/opensta-build/sta'
    parser.add_argument('--yosys', default='yowasp-yosys')
    parser.add_argument('--sta', default=str(default) if default.exists() else 'sta')


def iverilog_options(parameters):
    """Path delays, the delays of the nets, and the larger value of each SDF pair."""
    return ['-gspecify', '-ginterconnect', '-Tmax']


def site_library(text):
    """The teaching library with one more cell: TFSITE, a copy of BUF under another name."""
    start = text.index('cell(BUF)')
    depth, end = 0, start
    for end in range(text.index('{', start), len(text)):
        depth += (text[end] == '{') - (text[end] == '}')
        if depth == 0:
            break
    else:
        raise ValueError('cell(BUF) is not closed')
    cell = text[start:end + 1]
    if 'cell(TFSITE)' in text or cell.count('cell(') != 1:
        raise ValueError('unexpected library contents')
    return text[:end + 1] + '\n ' + cell.replace('cell(BUF)', 'cell(TFSITE)') + text[end + 1:]


def choose_period(need):
    """The shortest period, on a 0.05 ns grid, that the longest flop-to-flop path meets with a margin."""
    return math.ceil(round((need + MARGIN) / STEP, 6)) * STEP


def timing_module(period, sdf, limits, scope='tf_tb.dut'):
    lines = ['`timescale 1ns/1ps', '// Generated by run.py for this build.', 'module tf_timing;',
             f'    localparam real PERIOD = {period:.3f};', f'    initial $sdf_annotate("{sdf}", {scope});']
    lines += [f'    defparam {scope}.{name}.TSETUP = {setup}, {scope}.{name}.THOLD = {hold};'
              for name, (setup, hold) in sorted(limits.items())]
    return '\n'.join([*lines, 'endmodule', ''])


def sta_run(args, directory, name, variables):
    (directory / f'run-{name}.tcl').write_text(''.join(f'set {k} {v}\n' for k, v in variables.items()) + 'source check.tcl\n')
    execution = PROCESS.execute([args.sta, '-no_init', '-exit', f'run-{name}.tcl'], directory / f'{name}.log', args.timeout, directory)
    log = (directory / f'{name}.log').read_text(errors='replace')
    if execution['error'] or execution['returncode'] != 0 or re.search(r'^(?:Error:|TOOL_ERROR)', log, re.M):
        raise ValueError(f'OpenSTA failed; see {directory.name}/{name}.log')
    return log


def measure(log):
    slack = {mode: float(value) for mode, value in re.findall(r'^MEASURE (max|min) (\S+)$', log, re.M)}
    need = re.findall(r'^NEED (\S+)$', log, re.M)
    audit = re.findall(r'^AUDIT constraints ([01])$', log, re.M)
    if set(slack) != {'max', 'min'} or len(need) != 1 or audit != ['1'] or not re.search(r'^RESULT STA$', log, re.M):
        raise ValueError('incomplete static timing result or unconstrained endpoints')
    return dict(slack, need=float(need[0]))


def static_timing(args, directory, flops):
    """Measure the longest path, choose the period, require clean static timing, write the SDF file."""
    shutil.copy2(STA_SCRIPT, directory / 'check.tcl')
    need = measure(sta_run(args, directory, 'probe', dict(period=100, write_sdf=0)))['need']
    period = choose_period(need)
    given = measure(sta_run(args, directory, 'given', dict(period=f'{period:.3f}', write_sdf=1)))
    if min(given['max'], given['min']) < 0:
        raise ValueError('static timing fails at the chosen period')
    sdf = (directory / 'design.sdf').read_text()
    sites = set(re.findall(r'\(CELLTYPE "TFSITE"\)\s*\(INSTANCE (\w+)\)', sdf))
    if sites != {f'site_n{i}' for i in range(A.SITES)}:
        raise ValueError('SDF file does not hold the six fault sites')
    limits = G.check_limits(sdf, flops)
    report = dict(need=round(need, 3), period=round(period, 3), slack=dict(max=given['max'], min=given['min']), flops=len(limits))
    PROCESS.write_json(directory / 'timing.json', report)
    return report, timing_module(period, f'../{directory.name}/design.sdf', limits)


DESIGN_MUTATIONS = (3, 4)  # the others are in the bench: they use the netlist of the unchanged design
PREPARED = {}


def synthesize(args, mutation, directory):
    shutil.copy2(RTL, directory / RTL.name)
    shutil.copy2(LIBRARY, directory / 'gates.lib')
    (directory / 'cells.lib').write_text(site_library(LIBRARY.read_text()))
    version = PROCESS.execute([args.yosys, '-V'], directory / 'yosys-version.log', args.timeout * 6, directory)
    execution = PROCESS.execute([args.yosys, '-q', '-l', 'synthesis.log', '-p', SYNTHESIS.format(m=mutation)],
                                directory / 'yosys-console.log', args.timeout * 6, directory)
    execution.update(log=f'{directory.name}/yosys-console.log',
                     version=(directory / 'yosys-version.log').read_text(errors='replace').strip())
    if version['error'] or version['returncode'] != 0:
        execution['error'] = execution['error'] or 'yosys -V failed; see yosys-version.log'
    if execution['error'] or execution['returncode'] != 0:
        return execution
    try:
        netlist, flops = G.name_registers((directory / 'mapped.v').read_text())
        if len(flops) != 4 or len(re.findall(r'^\s*TFSITE site_n\d ', netlist, re.M)) != A.SITES:
            raise ValueError('netlist does not hold four flops and six fault sites')
        (directory / 'netlist.v').write_text(netlist)
        execution['static_timing'], module = static_timing(args, directory, flops)
        (directory / 'tf_timing.v').write_text(module)
    except (OSError, ValueError) as exc:
        execution['error'] = str(exc)
    return execution


def build_sources(args, configuration, parameters, mutation, directory):
    """A netlist with this design mutation fixed, its static timing and its SDF file.

    Both configurations and the bench mutations share one design, so the first build of a design
    is synthesized and timed; the later ones compile the same files and say where they come from."""
    design = mutation if mutation in DESIGN_MUTATIONS else 0
    key = (str(args.out), design)
    if key not in PREPARED:
        directory.mkdir()
        PREPARED[key] = (directory, synthesize(args, design, directory))
        origin, execution = PREPARED[key]
    else:
        origin, first = PREPARED[key]
        execution = dict(first, reused_from=origin.name)
    return [origin / 'netlist.v', CELLS, SITE_CELL, BENCH, origin / 'tf_timing.v'], execution


def stuck_response(q, x, fault, clocks):
    for _ in range(clocks):
        q = A.capture(q, x, fault)
    return q


def good_response(q, x, clocks):
    for _ in range(clocks):
        q = A.functional(q, x)
    return q


class Plan:
    """Rows of kind, state, x, clocks, site, fault kind, good response, expected detection, flags."""

    def __init__(self, gap):
        self.at_speed = gap == 1
        self.rows = []

    def flush(self, bits=FLUSH):
        self.rows.append([0, bits, 0, 0, 0, 0, 0, 0, 0])

    def fault_free(self, q, x, clocks):
        flags = 0
        if clocks == 2:
            first, second = A.nodes(q, x), A.nodes(A.functional(q, x), x)
            flags = any(a < b for a, b in zip(first, second)) | any(a > b for a, b in zip(first, second)) << 1
        self.rows.append([1, q, x, clocks, 0, 0, good_response(q, x, clocks), 0, flags])

    def stuck(self, q, x, fault, clocks=1):
        good = good_response(q, x, clocks)
        self.rows.append([1, q, x, clocks, fault[0], 1 + fault[1], good, int(stuck_response(q, x, fault, clocks) != good), 0])

    def transition(self, q, x, fault, untestable=False):
        """Detected only by a capture at speed. Rows whose outcome depends on a glitch are not planned."""
        if not A.hazard_free(q, x, fault):
            raise ValueError('the outcome of this row depends on a glitch')
        launched = A.launches(q, x, fault)
        detect = int(self.at_speed and A.transition_detects(q, x, fault))
        self.rows.append([1, q, x, 2, fault[0], 3 if fault[1] else 4, good_response(q, x, 2), detect,
                          launched << 2 | untestable << 3])


def transition_rows(plan):
    report = A.report()
    for fault in A.TRANSITION:
        for q, x in map(tuple, report['transition']['patterns']):
            if A.hazard_free(q, x, fault):
                plan.transition(q, x, fault)
    # The faults that no pattern detects: apply every pattern, and expect no detection.
    for item in report['transition']['undetectable']:
        for q, x in A.PATTERNS:
            if A.hazard_free(q, x, tuple(item['fault'])):
                plan.transition(q, x, tuple(item['fault']), untestable=True)


def boundary_vectors(gap):
    p = Plan(gap)
    p.flush()
    for q, x in A.PATTERNS:
        p.fault_free(q, x, 1)
        p.fault_free(q, x, 2)
    for fault in A.STUCK:
        for q, x in map(tuple, A.report()['stuck']['patterns']):
            p.stuck(q, x, fault)
    transition_rows(p)
    p.flush(FLUSH ^ 0xFF)
    return p.rows


def escape_vectors(gap):
    """Only the transition faults: what a slow capture lets through."""
    p = Plan(gap)
    p.flush()
    transition_rows(p)
    return p.rows


def random_vectors(seed, operations, gap):
    rng = random.Random(seed)
    p = Plan(gap)
    p.flush(rng.randrange(256))
    while len(p.rows) <= operations:
        q, x, roll = rng.randrange(16), rng.randrange(2), rng.random()
        if roll < 0.4:
            p.fault_free(q, x, rng.choice((1, 2)))
        elif roll < 0.65:
            p.stuck(q, x, rng.choice(A.STUCK), rng.choice((1, 2)))
        elif roll < 0.97:
            fault = rng.choice(A.TRANSITION)
            if A.hazard_free(q, x, fault):
                p.transition(q, x, fault)
        else:
            p.flush(rng.randrange(256))
    return p.rows


def counts(rows):
    faults = [row for row in rows if row[0] == 1 and row[5]]
    stuck = {(row[4], row[5]) for row in faults if row[5] <= 2}
    slow = {(row[4], row[5]) for row in faults if row[5] > 2}
    hit = {(row[4], row[5]) for row in faults if row[7]}
    return dict(fault_free=sum(row[0] == 1 and not row[5] for row in rows), stuck_applied=len(stuck),
                stuck_detected=len(stuck & hit), transition_applied=len(slow), transition_detected=len(slow & hit))


def make_cases(args, parameters):
    gap = parameters['GAP']
    name = next(key for key, value in CONFIGS.items() if value == parameters)
    base = boundary_vectors(gap)
    cases = [dict(id='boundaries', vectors=base, mutation=args.demo_bug, category='functional', expected_failure=None)]
    for seed in range(args.seed, args.seed + (3 if args.profile == 'nightly' else 1)):
        cases.append(dict(id=f'random-seed{seed}', vectors=random_vectors(seed, args.iterations, gap),
                          mutation=args.demo_bug, category='functional', expected_failure=None))
    if gap != 1:  # the same transition faults that the capture at speed detects, all missed
        cases.append(dict(id='escaped-transition-faults', vectors=escape_vectors(gap), mutation=0,
                          category='diagnostic', expected_failure=None))
    for mutation in range(1, MUTANTS + 1):
        if mutation in INVISIBLE.get(name, ()):
            cases.append(dict(id=f'invisible-mutation{mutation}', vectors=base, mutation=mutation,
                              category='diagnostic', expected_failure=None))
        else:
            cases.append(dict(id=f'detect-mutation{mutation}', vectors=base, mutation=mutation,
                              category='mutation', expected_failure=LABELS[mutation]))
    for case in cases:
        case['counts'] = counts(case['vectors'])
    return cases


