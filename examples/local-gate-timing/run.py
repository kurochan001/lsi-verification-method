BENCH = HERE / 'tb/mc_tb.sv'
SCRIPTS = [HERE / 'sta' / name for name in ('constraints.tcl', 'probe.tcl', 'check.tcl')]
SOURCES = [RTL, CELLS, BENCH]
EXTRA_INPUTS = [LIBRARY, *SCRIPTS]
LABELS = {1: 'MC_DATA', 2: 'MC_DATA', 3: 'MC_X'}
# What truthful constraints report for each mutant: the path group whose slack must be negative.
CORRECTED = {1: 'max', 2: 'max', 3: 'min'}
SETUP, MARGIN, STEP = 0.2, 0.1, 0.05
# Map to the cells of the library. Flops keep an enable pin, so that the data pin of the result
# register is not looked at while the product is still settling.
SYNTHESIS = ('read_liberty -lib cells.lib; read_verilog -sv mc_scale.sv; chparam -set MUTATION {m} mc_scale; '
             'synth -top mc_scale -flatten; dfflegalize -cell $_DFF_P_ x -cell $_DFFE_PP_ x; '
             'dfflibmap -liberty cells.lib; abc -liberty cells.lib; opt_clean; stat; '
             'write_verilog -noattr -noexpr mapped.v')
FLOP = re.compile(r'^(\s*)(DFFE?) (\S+) \((.*?\.Q\((.*?)\)\s*)\);', re.M | re.S)


def add_arguments(parser):
    default = ROOT / 'artifacts/toolchains/opensta-build/sta'
    parser.add_argument('--yosys', default='yowasp-yosys')
    parser.add_argument('--sta', default=str(default) if default.exists() else 'sta')


def iverilog_options(parameters):
    """Path delays, the delays of the nets, and the larger value of each SDF pair."""
    return ['-gspecify', '-ginterconnect', '-Tmax'] if parameters['GATE'] == 2 else []


def name_registers(netlist):
    """Call each flop after the net it drives, as a synthesis tool does: `a_q[3]` gives a_q_3_reg."""
    names = []

    def rename(match):
        name = re.sub(r'\W+', '_', match.group(5)).strip('_') + '_reg'
        names.append(name)
        return f'{match.group(1)}{match.group(2)} {name} ({match.group(4)});'
    text = FLOP.sub(rename, netlist).replace('\\g_skew.skew ', 'skew')
    if len(set(names)) != len(names) or len(names) != len(re.findall(r'^\s*DFFE? ', netlist, re.M)):
        raise ValueError('flops could not be named after their outputs')
    return text, names


def check_limits(sdf, flops):
    """TSETUP and THOLD of every flop, from the TIMINGCHECK entries of the SDF file."""
    limits = {}
    for cell in re.split(r'\(CELL\b', sdf)[1:]:
        instance = re.search(r'\(INSTANCE (\w+)\)', cell)
        if not instance or not re.search(r'\(CELLTYPE "DFFE?"\)', cell):
            continue
        values = {kind: {float(v) for v in re.findall(r'\(%s \w+ \(posedge CLK\) \([\d.]*::([\d.]+)\)\)' % kind, cell)}
                  for kind in ('SETUP', 'HOLD')}
        if any(len(found) != 1 for found in values.values()):
            raise ValueError(f'no single setup and hold value for {instance.group(1)}')
        limits[instance.group(1)] = (values['SETUP'].pop(), values['HOLD'].pop())
    if set(limits) != set(flops):
        raise ValueError('SDF timing checks do not cover every flop')
    return limits


def timing_module(period, cfg_at, sdf=None, limits=None, scope='mc_tb.g_gate.dut'):
    lines = ['`timescale 1ns/1ps', '// Generated by run.py for this build.', 'module mc_timing;',
             f'    localparam real PERIOD = {period:.3f}, CFG_AT = {cfg_at:.3f};']
    if sdf:
        lines.append(f'    initial $sdf_annotate("{sdf}", {scope});')
        lines += [f'    defparam {scope}.{name}.TSETUP = {setup}, {scope}.{name}.THOLD = {hold};'
                  for name, (setup, hold) in sorted(limits.items())]
    return '\n'.join([*lines, 'endmodule', ''])


def choose_period(need):
    """The shortest period, on a 0.05 ns grid, that every group of paths meets with a margin."""
    floor = max(need['multicycle'] / 2, need['single'], 2 * need['input']) + MARGIN
    return math.ceil(round(floor / STEP, 6)) * STEP


def sta_run(args, directory, name, script, variables):
    (directory / f'run-{name}.tcl').write_text(''.join(f'set {k} {v}\n' for k, v in variables.items()) + f'source {script}\n')
    execution = PROCESS.execute([args.sta, '-no_init', '-exit', f'run-{name}.tcl'], directory / f'{name}.log', args.timeout, directory)
    log = (directory / f'{name}.log').read_text(errors='replace')
    if execution['error'] or execution['returncode'] != 0 or re.search(r'^(?:Error:|TOOL_ERROR)', log, re.M):
        raise ValueError(f'OpenSTA failed; see {directory.name}/{name}.log')
    return log


def measure(log):
    slack = {mode: float(value) for mode, value in re.findall(r'^MEASURE (max|min) (\S+)$', log, re.M)}
    audit = re.findall(r'^AUDIT constraints ([01])$', log, re.M)
    if set(slack) != {'max', 'min'} or len(audit) != 1 or not re.search(r'^RESULT STA$', log, re.M):
        raise ValueError('incomplete static timing result')
    return dict(slack, audit=int(audit[0]))


def static_timing(args, directory, mutation, flops):
    """Choose the period, require clean static timing under the given constraints, write the SDF file."""
    for path in (LIBRARY, *SCRIPTS):
        shutil.copy2(path, directory / ('cells.lib' if path == LIBRARY else path.name))
    need = {name: float(value) for name, value in re.findall(r'^NEED (\w+) (\S+)$', sta_run(args, directory, 'probe', 'probe.tcl', {}), re.M)}
    if set(need) != {'multicycle', 'cfg', 'input', 'single'}:
        raise ValueError('incomplete probe of the path groups')
    period = choose_period(need)
    if need['multicycle'] - SETUP <= period + MARGIN:
        raise ValueError('the product path fits one period: the design no longer needs its multicycle path')
    # Mutant 2: cfg reaches its flop in the middle of the setup window of the start cycle.
    cfg_at = period - SETUP / 2 - (need['cfg'] - SETUP) if mutation == 2 else period / 2
    variables = dict(period=f'{period:.3f}', cfg_delay=f'{cfg_at:.3f}', mutation=mutation)
    given = measure(sta_run(args, directory, 'given', 'check.tcl', dict(variables, corrected=0, write_sdf=1)))
    if min(given['max'], given['min']) < 0:
        raise ValueError('static timing fails under the given constraints')
    # The false path of mutant 2 leaves the data pin of the cfg flop unconstrained: the audit says so.
    if given['audit'] != (mutation != 2):
        raise ValueError('unexpected result of the constraint audit')
    report = dict(need=need, period=round(period, 3), cfg_at=round(cfg_at, 3), given_slack=given)
    if mutation:
        corrected = measure(sta_run(args, directory, 'corrected', 'check.tcl', dict(variables, corrected=1, write_sdf=0)))
        if corrected[CORRECTED[mutation]] >= 0 or not corrected['audit']:
            raise ValueError('truthful constraints do not report this mutant')
        report.update(corrected_slack=corrected)
    limits = check_limits((directory / 'design.sdf').read_text(), flops)
    PROCESS.write_json(directory / 'timing.json', dict(report, flops=len(limits)))
    return report, timing_module(period, cfg_at, f'../{directory.name}/design.sdf', limits)


def build_sources(args, configuration, parameters, mutation, directory):
    """The RTL, or a netlist mapped with this mutation fixed; for `sdf` also its timing and SDF file."""
    directory.mkdir()
    timing = directory / 'mc_timing.v'
    execution = dict(command=[], returncode=0, error=None, seconds=0)
    if not parameters['GATE']:
        timing.write_text(timing_module(10, 9 if mutation == 2 else 5))
        return [*SOURCES, timing], execution
    shutil.copy2(RTL, directory / RTL.name)
    shutil.copy2(LIBRARY, directory / 'cells.lib')
    version = PROCESS.execute([args.yosys, '-V'], directory / 'yosys-version.log', args.timeout * 6, directory)
    execution = PROCESS.execute([args.yosys, '-q', '-l', 'synthesis.log', '-p', SYNTHESIS.format(m=mutation)],
                                directory / 'yosys-console.log', args.timeout * 6, directory)
    execution.update(log=f'{directory.name}/yosys-console.log',
                     version=(directory / 'yosys-version.log').read_text(errors='replace').strip())
    if version['error'] or version['returncode'] != 0:
        execution['error'] = execution['error'] or 'yosys -V failed; see yosys-version.log'
    if execution['error'] or execution['returncode'] != 0:
        return [], execution
    try:
        netlist, flops = name_registers((directory / 'mapped.v').read_text())
        (directory / 'netlist.v').write_text(netlist)
        if parameters['GATE'] == 2:
            execution['static_timing'], module = static_timing(args, directory, mutation, flops)
        else:
            module = timing_module(10, 9 if mutation == 2 else 5)
        timing.write_text(module)
    except (OSError, ValueError) as exc:
        execution['error'] = str(exc)
    return [directory / 'netlist.v', CELLS, BENCH, timing], execution


def expected(a, b, cfg):
    return (a * b) << cfg


class Plan:
    """Rows of kind, a, b, cfg, idle cycles before the start, expected result."""

    def __init__(self):
        self.rows = []

    def reset(self):
        self.rows.append([0, 0, 0, 0, 0, 0])

    def operation(self, a, b, cfg=0, gap=0, cut=False):
        self.rows.append([2, a, b, cfg, gap, 0] if cut else [1, a, b, cfg, gap, expected(a, b, cfg)])


def boundary_vectors():
    p = Plan()
    p.reset()
    p.operation(0, 0, gap=2)
    p.operation(63, 63)                  # every product bit moves: the longest settling
    p.operation(63, 63, cfg=1)           # cfg changes in the start cycle
    p.operation(1, 63, cfg=1)
    p.operation(63, 1, cfg=0, gap=3)     # cfg changes while idle
    p.operation(0, 63)
    p.operation(43, 21, cfg=1, gap=1)
    p.operation(21, 43, cfg=0)
    p.operation(42, 63, cut=True)        # reset during the operation
    p.operation(42, 63)
    p.operation(63, 42, cfg=1)
    p.operation(32, 32, cfg=1, gap=4)
    p.operation(31, 33)
    return p.rows


def random_vectors(seed, operations):
    rng = random.Random(seed)
    p = Plan()
    p.reset()
    while len(p.rows) <= operations:
        roll = rng.random()
        if roll < 0.02:
            p.reset()
            continue
        a, b = (rng.choice((0, 1, 62, 63)) if rng.random() < 0.2 else rng.randrange(64) for _ in range(2))
        p.operation(a, b, cfg=rng.randrange(2), gap=rng.choice((0, 0, 1, 2, 5)), cut=roll < 0.06)
    return p.rows


def counts(rows):
    return dict(operations=sum(row[0] == 1 for row in rows), aborted=sum(row[0] == 2 for row in rows),
                timing_violations=0)


def make_cases(args, parameters):
    base = boundary_vectors()
    cases = [dict(id='boundaries', vectors=base, mutation=args.demo_bug, category='functional',
                  expected_failure=None)]
    for seed in range(args.seed, args.seed + (3 if args.profile == 'nightly' else 1)):
        cases.append(dict(id=f'random-seed{seed}', vectors=random_vectors(seed, args.iterations),
                          mutation=args.demo_bug, category='functional', expected_failure=None))
    for mutation in range(1, MUTANTS + 1):
        if parameters['GATE'] == 2:
            cases.append(dict(id=f'detect-mutation{mutation}', vectors=base, mutation=mutation,
                              category='mutation', expected_failure=LABELS[mutation]))
        else:  # without delays the same mutant passes, in the RTL and in the netlist
            cases.append(dict(id=f'invisible-mutation{mutation}', vectors=base, mutation=mutation,
                              category='diagnostic', expected_failure=None))
    for case in cases:
        case['counts'] = counts(case['vectors'])
    return cases


