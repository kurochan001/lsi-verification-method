MUTANTS = 3
CONFIGS = {'rtl': {'GATE': 0}, 'gate': {'GATE': 1}, 'sdf': {'GATE': 2}}
ITERATIONS = {'smoke': 80, 'nightly': 800}
RTL = HERE / 'rtl/mc_scale.sv'
CELLS = HERE / 'cells/cells.v'
