#!/usr/bin/env python3
"""Generate the RV32I specification decoder from the riscv-opcodes tables.

RV32I is every non-pseudo line of upstream/rv_i plus the RV32 shift encodings that
upstream/rv32_i gives as pseudo-ops of the RV64 shifts. Each line becomes a mask and a
match value; every bit of the instruction word must be either fixed or an operand.
"""
import argparse
import hashlib
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
UPSTREAM = [HERE / 'upstream/rv_i', HERE / 'upstream/rv32_i']
SPEC = HERE / 'spec_decode.sv'
# Operand fields of riscv-opcodes (arg_lut.csv) that RV32I uses: name -> (high bit, low bit).
FIELDS = {'rd': (11, 7), 'rs1': (19, 15), 'rs2': (24, 20), 'imm12': (31, 20), 'imm12hi': (31, 25),
          'imm12lo': (11, 7), 'bimm12hi': (31, 25), 'bimm12lo': (11, 7), 'imm20': (31, 12), 'jimm20': (31, 12),
          'fm': (31, 28), 'pred': (27, 24), 'succ': (23, 20), 'shamtw': (24, 20)}
# Immediate of each format, as the base ISA's immediate encoding figure assembles it.
IMMEDIATE = {'I': "{{20{insn[31]}}, insn[31:20]}",
             'S': "{{20{insn[31]}}, insn[31:25], insn[11:7]}",
             'B': "{{19{insn[31]}}, insn[31], insn[7], insn[30:25], insn[11:8], 1'b0}",
             'U': "{insn[31:12], 12'b0}",
             'J': "{{11{insn[31]}}, insn[31], insn[19:12], insn[20], insn[30:21], 1'b0}",
             'SHIFT': "{27'b0, insn[24:20]}", 'R': "32'b0", 'NONE': "32'b0"}
# FENCE carries rs1 and rd fields that base implementations must ignore (ISA manual, FENCE).
IGNORED_REGISTERS = {'fence'}


class TableError(ValueError):
    pass


def parse_line(tokens):
    name, rest = tokens[0], tokens[1:]
    mask = match = covered = 0
    args = []
    for token in rest:
        if '=' in token:
            bits, value = token.split('=')
            high, low = (int(b) for b in bits.split('..')) if '..' in bits else (int(bits), int(bits))
            width = high - low + 1
            value = int(value, 0)
            if value >> width:
                raise TableError(f'{name}: {token} does not fit its field')
            field = ((1 << width) - 1) << low
            if mask & field:
                raise TableError(f'{name}: {token} overlaps another fixed field')
            mask, match = mask | field, match | value << low
        elif token in FIELDS:
            high, low = FIELDS[token]
            covered |= ((1 << (high - low + 1)) - 1) << low
            args.append(token)
        else:
            raise TableError(f'{name}: unknown operand {token}')
    if mask & covered or (mask | covered) != 0xffffffff:
        raise TableError(f'{name}: fixed fields and operands do not cover the word exactly once')
    return dict(name=name, mask=mask, match=match, args=args)


def table(paths=UPSTREAM):
    entries = []
    for path in paths:
        for line in path.read_text().splitlines():
            tokens = line.split()
            if not tokens or tokens[0].startswith('#'):
                continue
            if tokens[0] == '$pseudo_op':
                origin, tokens = tokens[1], tokens[2:]
                # rv32_i defines the RV32 shifts as pseudo-ops of the RV64 ones under the same name.
                if path.name != 'rv32_i' or origin.split('::')[1] != tokens[0]:
                    continue
            entries.append(parse_line(tokens))
    for i, a in enumerate(entries):
        for b in entries[i + 1:]:
            if not (a['match'] ^ b['match']) & a['mask'] & b['mask']:
                raise TableError(f"{a['name']} and {b['name']} share encodings")
    return entries


def describe(entry):
    """Format, and which of rd / rs1 / rs2 the instruction writes or reads."""
    args = set(entry['args'])
    form = ('U' if 'imm20' in args else 'J' if 'jimm20' in args else 'B' if 'bimm12hi' in args else
            'S' if 'imm12hi' in args else 'SHIFT' if 'shamtw' in args else 'I' if args & {'imm12', 'fm'} else
            'R' if 'rs2' in args else 'NONE')
    ignored = entry['name'] in IGNORED_REGISTERS
    return form, ('rd' in args and not ignored, 'rs1' in args and not ignored, 'rs2' in args)


def decode(entries, word):
    """Python form of the specification: (index, format, registers) or None for an illegal word."""
    for i, entry in enumerate(entries):
        if word & entry['mask'] == entry['match']:
            return (i, *describe(entry))
    return None


def fingerprint(paths=UPSTREAM):
    digest = hashlib.sha256()
    for path in paths:
        digest.update(path.read_bytes())
    return digest.hexdigest()


def render(entries=None):
    entries = table() if entries is None else entries
    n = len(entries)
    lines = ['// Generated by generate.py from upstream/rv_i and upstream/rv32_i (riscv-opcodes). Do not edit by hand.',
             f'// Inputs: {fingerprint()}']
    lines += [f"`define RV32I_{e['name'].upper()} {i}" for i, e in enumerate(entries)]
    lines += [f'module rv32i_spec(input wire [31:0] insn, output wire [{n-1}:0] hit, output wire legal,',
              '                  output reg [5:0] index, output reg [31:0] imm, output reg rd_we, rs1_used, rs2_used);']
    for i, e in enumerate(entries):
        lines.append(f"    assign hit[{i}] = (insn & 32'h{e['mask']:08x}) == 32'h{e['match']:08x};  // {e['name']}")
    lines += ['    assign legal = |hit;', '    always @* begin',
              "        index = 6'd0; imm = 32'b0; {rd_we, rs1_used, rs2_used} = 3'b000;"]
    for i, e in enumerate(entries):
        form, regs = describe(e)
        bits = ''.join(str(int(r)) for r in regs)
        lines.append(f"        if (hit[{i}]) begin index = 6'd{i}; imm = {IMMEDIATE[form]}; "
                     f"{{rd_we, rs1_used, rs2_used}} = 3'b{bits}; end  // {e['name']} {form}")
    lines += ['    end', 'endmodule']
    return '\n'.join(lines) + '\n'


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true', help='fail when spec_decode.sv is out of date')
    args = p.parse_args()
    try:
        text = render()
    except TableError as exc:
        print('TABLE_ERROR', exc, file=sys.stderr)
        return 1
    if args.check:
        current = SPEC.exists() and SPEC.read_text() == text
        print('spec_decode.sv is', 'current' if current else 'out of date')
        return 0 if current else 1
    SPEC.write_text(text)
    print('wrote', SPEC.relative_to(HERE))
    return 0


if __name__ == '__main__':
    sys.exit(main())
