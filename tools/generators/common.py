"""What the generators share: the form of a generated test and how the tests
are written to tests/gen/.

A generator is a module with NAME, VERSION, CHAPTER and a function cases()
that returns Case objects. Each case becomes tests/gen/chNN/<name>.sv and
<name>.expected, where NN is the chapter of the case if it gives one and the
CHAPTER of the generator otherwise, where the expected output comes from the generator's
reference model, which is written from the clauses of IEEE 1800-2023 and
does not use any simulator. A case with should_fail_because is an illegal
design: it has no .expected file, and :expected_stderr_regex: names the line
of its body that ends with "// illegal".

The :oracle: of a generated test is "spec" followed by the simulators that
were found to produce its expected output; generators/oracles.txt records
them (tools in the README, "Generated tests").
"""

import textwrap
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GEN = ROOT / "tests" / "gen"
ORACLES = Path(__file__).resolve().parent / "oracles.txt"


@dataclass
class Case:
    name: str                 # test_gen_<generator>_<what>, unique
    description: str          # one line for :description:
    lrm: str                  # clauses, the first one first, such as "11.6.1 11.8.2"
    comment: str              # what the case checks, wrapped into // lines
    body: str                 # the design, without the metadata comment
    expected: str             # the expected standard output
    fourstate: bool = False
    extra: dict = field(default_factory=dict)   # other metadata fields
    chapter: int | None = None                   # the generator's CHAPTER if None
    # For an illegal design: the reason, and no expected output. The line of
    # the body that ends with "// illegal" names the error in
    # :expected_stderr_regex:.
    should_fail_because: str | None = None


def read_oracles() -> dict[str, str]:
    if not ORACLES.exists():
        return {}
    oracles = {}
    for line in ORACLES.read_text().splitlines():
        if line.strip() and not line.startswith("#"):
            name, oracle = line.split(None, 1)
            oracles[name] = oracle
    return oracles


def render(case: Case, generator: str, version: int, chapter: int,
           oracle: str) -> tuple[str, str]:
    """The text of the test and of its expected output (None for an illegal
    design)."""
    first = case.lrm.split()[0]
    illegal = case.should_fail_because is not None
    head = ["/*",
            f":name: {case.name}",
            f":description: {case.description} (IEEE 1800-2023 Section {first})",
            f":tags: ch{chapter}",
            f":type: {'elaboration' if illegal else 'simulation'}",
            f":lrm: 1800-2023 {case.lrm}",
            f":oracle: {oracle}",
            ":spec_check: ai",
            f":fourstate: {'yes' if case.fourstate else 'no'}",
            ":nondeterministic: no",
            f":generator: {generator}@{version}"]
    head += [f":{k}: {v}" for k, v in case.extra.items()]
    if illegal:
        head += [f":should_fail_because: {case.should_fail_because}",
                 ":expected_stderr_regex: {line}", "*/"]
    else:
        head += [f":expected_stdout: @{case.name}.expected", "*/"]
    note = [f"// Generated by generators/{generator}.py; edit it, not this file."]
    comment = ["// " + l for l in textwrap.wrap(case.comment, 77)]
    lines = head + note + comment + [""] + case.body.strip("\n").splitlines()
    if illegal:
        marked = [n for n, l in enumerate(lines, 1) if l.rstrip().endswith("// illegal")]
        assert len(marked) == 1, case.name
        lines[head.index(":expected_stderr_regex: {line}")] = (
            f":expected_stderr_regex: {case.name}\\.sv:{marked[0]}:")
    text = "\n".join(lines) + "\n"
    for line in text.splitlines()[len(head):]:
        limit = 80 if line.lstrip().startswith("//") else 100
        assert len(line) <= limit, (case.name, line)
    return text, None if illegal else case.expected


def outputs(generators) -> dict[Path, str]:
    """Every file the generators write, by path."""
    oracles = read_oracles()
    files = {}
    for g in generators:
        names = set()
        for case in g.cases():
            assert case.name not in names, case.name
            names.add(case.name)
            chapter = case.chapter or g.CHAPTER
            directory = GEN / f"ch{chapter}"
            text, expected = render(case, g.NAME, g.VERSION, chapter,
                                    oracles.get(case.name, "spec"))
            files[directory / f"{case.name}.sv"] = text
            if expected is not None:
                files[directory / f"{case.name}.expected"] = expected
    return files
